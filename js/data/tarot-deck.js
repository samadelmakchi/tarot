function buildMinor() {
  const cards = [];
  let counter = 22;
  for (const [sKey, suit] of Object.entries(SUITS)) {
    const imageSuit = sKey === "coins" ? "pentacles" : sKey;
    for (let n = 0; n < 10; n++) {
      const num = n + 1;
      cards.push({
        id: `minor-${sKey}-${num}`,
        image: `img/${RANK_FILE[n]}-of-${imageSuit}.jpg`,
        no: fa(counter),
        name: `${suit.name} ${RANK_NUM[n]}`,
        sym: suit.sym,
        kind: "minor",
        suit: suit.name,
        domain: suit.domain,
        key: `${suit.domain} — ${num === 1 ? "آغاز" : num === 5 ? "تنش" : num === 10 ? "فرجام" : "روند"}`,
        upright: suit.pos[n],
        reversed: suit.neg[n % suit.neg.length],
        _rank: num,
      });
      counter++;
    }
    for (const c of COURT) {
      cards.push({
        id: `minor-${sKey}-${c.kind}`,
        image: `img/${c.kind}-of-${imageSuit}.jpg`,
        no: fa(counter),
        name: `${c.name}ٔ ${suit.name}`,
        sym: suit.sym,
        kind: "court",
        suit: suit.name,
        domain: suit.domain,
        key: `${c.role} در قلمروی ${suit.domain}`,
        upright: `شخصیتی یا جنبه‌ای از ${c.role} در قلمروی ${suit.domain} در حال شکل‌گیری است.`,
        reversed: `${c.role} در قلمروی ${suit.domain} با افراط یا ناپختگی همراه شده است؛ به تعادل برگرد.`,
      });
      counter++;
    }
  }
  return cards;
}

function fa(n) {
  return String(n).replace(/[0-9]/g, (d) => "۰۱۲۳۴۵۶۷۸۹"[+d]);
}

function buildMajor() {
  return MAJOR.map((m, idx) => ({ ...m, id: `major-${idx}`, image: `img/${MAJOR_FILE[idx]}.jpg`, kind: "major", _rank: idx }));
}

/** ساخت کامل ۷۸ کارت */
export function fullDeck() {
  return [...buildMajor(), ...buildMinor()];
}

/** فقط ۲۲ کارت کبیر */
export function majorDeck() {
  return buildMajor();
}

/** فقط ۵۶ کارت صغیر */
export function minorDeck() {
  return buildMinor();
}

/** با مختلط‌کردن، دسته‌ای برمی‌گرداند */
export function shuffledDeck(deck) {
  const a = deck.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

