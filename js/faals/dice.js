function page(mount) {
  const box = falPage(mount, meta, () => {});
  actionFlow(box, {
    note: "بر نیتت متمرکز شو و دو تاس را بینداز.",
    btnLabel: "🎲 انداختن تاس‌ها",
    againLabel: "پرتاب دوباره",
    busyLabel: "در حال پرتاب…",
    suspense: [900, 1800],
  }, (result) => {
    const d1 = 1 + Math.floor(Math.random() * 6);
    const d2 = 1 + Math.floor(Math.random() * 6);
    const dice = [d1, d2];
    const face = { 1: "⚀", 2: "⚁", 3: "⚂", 4: "⚃", 5: "⚄", 6: "⚅" };
    const r = RESULTS[d1 + d2];
    const diceEl = el("div", { class: "center reveal", style: "font-size:64px;letter-spacing:10px;color:var(--gold-soft);",
      text: `${face[dice[0]]}  ${face[dice[1]]}` });
    result.append(diceEl,
      el("div", { class: "center reveal" },
        el("div", { class: "big-answer", text: r.v }),
        el("p", { class: "muted", text: r.t }),
      ),
    );
  });
}

export default { meta, page };
