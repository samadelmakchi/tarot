function page(mount) {
  const box = falPage(mount, meta, () => {});
  const note = el("p", { class: "lead-note muted", text: "نیت کن و کتابی را که دلت می‌کشد برگزین؛ سطر راستِ همان صفحه، پیام توست." });
  const btn = el("button", { class: "btn big breathe", text: "📖 گشودن کتاب" });
  const result = el("div", { class: "result-box reveal", hidden: true });
  box.append(note, el("div", { class: "center" }, btn), result);

  btn.addEventListener("click", async () => {
    btn.disabled = true;
    btn.textContent = "در حال گشودن کتاب…";
    result.hidden = true;
    await delay(1500 + Math.random() * 900);
    const p = PASSAGES[Math.floor(Math.random() * PASSAGES.length)];
    btn.disabled = false;
    btn.textContent = "فال دوباره";
    result.hidden = false;
    const lines = el("div", { class: "ghazal" });
    p.lines.forEach(([a, b]) => {
      lines.append(el("span", { class: "bayt" }, el("span", { class: "m1", text: a }), b ? el("span", { text: "  ✦  " }) : null, b ? el("span", { class: "m2", text: b }) : null));
    });
    result.append(
      el("p", { class: "dim center reveal", text: `فال کتاب — ${p.book}` }),
      lines,
      el("div", { class: "panel reveal" }, el("h3", { text: "پیام برای تو" }), el("p", { text: p.text })),
    );
    result.scrollIntoView({ behavior: "smooth", block: "nearest" });
  });
}

export default { meta, page };
