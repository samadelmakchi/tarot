function page(mount) {
  const box = falPage(mount, meta, () => {});
  const note = el("p", { class: "lead-note muted", text: "با قرائت فاتحه‌ای برای حافظ، نیتت را در دل بگذران و فال حافظت را بگیر." });
  const btn = el("button", { class: "btn big breathe", text: "🌸 گرفتن فال حافظ" });
  const result = resultWrap();
  box.append(note, el("div", { class: "center" }, btn), result);

  btn.addEventListener("click", async () => {
    btn.disabled = true;
    btn.textContent = "در حال تفأل…";
    result.hidden = true;
    await delay(1300 + rnd() * 800);
    const g = GHAZALS[Math.floor(rnd() * GHAZALS.length)];
    btn.disabled = false;
    btn.textContent = "فال دوباره";

    const dateLine = el("p", { class: "dim center", text: `فال حافظ — ${faToday()}` });
    const ghazal = el("div", { class: "ghazal" });
    g.beyt.forEach(([m1, m2]) => {
      ghazal.append(
        el("span", { class: "bayt" },
          el("span", { class: "m1", text: m1 }),
          el("span", { text: "  ✦  " }),
          el("span", { class: "m2", text: m2 }),
        ),
      );
    });
    const interp = el("div", { class: "panel reveal" },
      el("h3", { text: `تفسیر — ${g.key}` }),
      el("p", { text: g.text }),
      el("p", { class: "gold", text: `✦ ${g.advice}` }),
    );
    result.hidden = false;
    result.innerHTML = "";
    result.append(dateLine, ghazal, interp,
      el("div", { class: "center" }, el("button", {
        class: "btn ghost", text: "کپی فال", style: "padding:9px 18px;font-size:14px;",
        onclick: async () => {
          const { copyText } = await import("../lib/util.js");
          copyText(`فال حافظ — ${faToday()}\n${g.beyt.map((b) => b.join(" / ")).join("\n")}\n\nتفسیر: ${g.text}\n${g.advice}`);
        },
      })),
    );
    result.scrollIntoView({ behavior: "smooth", block: "nearest" });
  });
}

export default { meta, page };
