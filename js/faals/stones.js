function page(mount) {
  const box = falPage(mount, meta, () => {});
  const grid = el("div", { class: "faal-grid", style: "margin-bottom:8px" });
  STONES.forEach((s) => {
    grid.append(el("button", {
      class: "faal-card", style: "--accent:#7dd3fc",
      onclick: () => show(s),
    },
      el("span", { class: "em", text: s.c }),
      el("span", { class: "ttl", text: s.n }),
      el("span", { class: "dsc", text: s.m }),
    ));
  });
  box.append(grid);
  function show(s) {
    const prev = document.querySelector(".sel-stone");
    if (prev) prev.remove();
    const panel = el("div", { class: "panel sel-stone reveal" },
      el("h3", { text: `${s.c} ${s.n}` }),
      el("p", { text: s.m }),
      el("p", { class: "dim", text: "در سنت کهن، سنگ‌ها را پس از استفاده با آب و نور ماه پاک می‌کنند." }),
    );
    box.append(panel);
    panel.scrollIntoView({ behavior: "smooth", block: "nearest" });
  }
}

