function page(mount) {
  const box = falPage(mount, meta, () => {});
  const input = el("input", { type: "date", max: "2020-01-01", min: "1900-01-01", value: "1995-06-15" });
  const field = el("div", { class: "field", style: "max-width:420px;margin-inline:auto" }, el("label", { text: "تاریخ تولد (میلادی)" }), input);
  const btn = el("button", { class: "btn big", text: "🔢 محاسبهٔ عدد زندگی" });
  const result = el("div", { class: "result-box reveal", hidden: true });
  box.append(el("div", { class: "row-inputs" }, field, el("div", { class: "center" }, btn)), result);

  btn.addEventListener("click", () => {
    const v = input.value;
    if (!v) return;
    const [y, m, d] = v.split("-").map(Number);
    const digits = String(y) + String(m) + String(d);
    let num = digits.split("").reduce((a, c) => a + +c, 0);
    while (num > 9 && num !== 11 && num !== 22 && num !== 33) {
      num = String(num).split("").reduce((a, c) => a + +c, 0);
    }
    const M = MEANINGS[num];
    const z = zodiacFromMD(m, d);
    result.hidden = false;
    result.innerHTML = "";
    result.append(
      el("div", { class: "center reveal" },
        el("div", { class: "stat-card", style: "max-width:300px;margin-inline:auto" },
          el("div", { class: "n", text: faNum(num) }),
          el("div", { class: "l", text: M.t }),
        ),
        el("p", { class: "muted", text: `کلیدواژه: ${M.c}` }),
        el("div", { class: "read-item", style: "text-align:right;margin-top:10px" },
          el("h4", { text: "مسیر زندگی تو" }),
          el("p", { text: M.d }),
          el("p", { class: "gold", text: M.ch }),
        ),
        el("p", { class: "dim", style: "margin-top:12px", text: `متولد ${faNum(d)}/${faNum(m)}/${faNum(y)} — ${z.name} (${z.en})` }),
      ),
    );
    result.scrollIntoView({ behavior: "smooth", block: "nearest" });
  });
}

export default { meta, page };
