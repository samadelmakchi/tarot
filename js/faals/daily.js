function page(mount) {
  const box = falPage(mount, meta, () => {});
  const saved = Number(localStorage.getItem("faalbin-daily") || 0);

  const picker = el("div", { class: "row-inputs" });
  const monthSel = el("select", { id: "monthSel" });
  SIGNS.forEach((s, i) => monthSel.append(el("option", { value: i, text: `${s.emoji} ${s.m} — ${s.en}` })));
  monthSel.value = saved;
  const selWrap = el("div", { class: "field" }, el("label", { text: "ماه تولدت را انتخاب کن" }), monthSel);
  const btn = el("button", { class: "btn big", text: "🔮 خواندن فال روزانه" });
  picker.append(selWrap, el("div", { class: "center" }, btn));
  const result = el("div", { class: "result-box reveal", hidden: true });
  box.append(picker, result);

  function render() {
    const i = Number(monthSel.value);
    localStorage.setItem("faalbin-daily", String(i));
    const sign = SIGNS[i];
    const today = todayJalali();
    const seed = `${today.year}-${today.month}-${today.day}-${i}`;
    const rng = seeded(seed);
    const rating = RATINGS[Math.floor(rng() * RATINGS.length)];
    const opener = OPENERS[Math.floor(rng() * OPENERS.length)];
    const tip = TIPS[Math.floor(rng() * TIPS.length)];

    result.hidden = false;
    result.innerHTML = "";
    const head = el("div", { class: "center reveal" },
      el("h2", { style: "margin-bottom:4px", text: `${sign.emoji} فال روزانهٔ متولدین ${sign.m} — برج ${sign.en}` }),
      el("p", { class: "dim", text: `تاریخ: ${faToday()}` }),
      el("p", { class: "muted", text: opener }),
      el("div", { class: "stat-card", style: "margin-top:12px" },
        el("div", { class: "n", text: "★".repeat(rating.n) }),
        el("div", { class: "l", text: rating.t }),
      ),
    );
    const topics = [
      ["💞 عشق و روابط", sign.topics.love],
      ["🌿 سلامتی و تندرستی", sign.topics.health],
      ["💰 پول و امور مالی", sign.topics.money],
      ["💼 شغل و کسب‌وکار", sign.topics.work],
    ].map(([t, txt]) => el("div", { class: "read-item" }, el("h4", { text: t }), el("p", { text: txt })));
    const section = el("div", { class: "reading reveal" }, ...topics);
    const tipLine = el("div", { class: "panel reveal" },
      el("h3", { text: "✨ نکتهٔ امروز" }),
      el("p", { text: tip }),
    );
    result.append(head, el("hr", { class: "divider" }), section, tipLine,
      el("div", { class: "center" }, el("button", {
        class: "btn ghost", text: "کپی فال امروز", style: "padding:9px 18px;font-size:14px;",
        onclick: async () => {
          const { copyText } = await import("../lib/util.js");
          const txt = [`فال روزانه — ${faToday()}`, `${sign.emoji} متولدین ${sign.m} (${sign.en})`, `${rating.n} ستاره — ${rating.t}`, "",
            ...topics.map((it, k) => `${["عشق و روابط", "سلامتی", "پول و امور مالی", "شغل"][k]}:\n${[sign.topics.love, sign.topics.health, sign.topics.money, sign.topics.work][k]}`),
            "", `✨ ${tip}`, "", "فال‌بین — جامع‌ترین فال‌های آنلاین"].join("\n");
          copyText(txt, "فال کپی شد ✓");
        },
      })),
    );
    result.scrollIntoView({ behavior: "smooth", block: "nearest" });
  }

  btn.addEventListener("click", render);
  render();
}

export default { meta, page };
