function page(mount) {
  const box = falPage(mount, meta, () => {});
  actionFlow(box, {
    note: "نیت کن و یک رون از کیسه بردار (راست = راست، وارونه = معکوس).",
    btnLabel: "🪵 برداشتن رون",
    againLabel: "رون دوباره",
    busyLabel: "در حال هم‌زدن رون‌ها…",
    suspense: [1100, 2000],
  }, (result) => {
    const rune = RUNES[Math.floor(Math.random() * RUNES.length)];
    const reversed = Math.random() < 0.25;
    result.append(el("div", { class: "center reveal" },
      el("div", { style: "font-size:88px;color:var(--gold-soft);" + (reversed ? "transform:rotate(180deg);display:inline-block;" : ""), text: rune.r }),
      el("div", { style: "font-size:18px;font-weight:800;color:var(--text)", text: `${rune.n}${reversed ? " (معکوس)" : ""}` }),
      el("p", { class: "dim", text: `کلیدواژه: ${rune.k}` }),
      el("p", { class: "muted", style: "max-width:520px;margin-inline:auto", text: reversed ? `چالشِ ${rune.k}: ${rune.m} در این حالت، از تو تأمل و بازبینی می‌خواهد.` : rune.m }),
    ));
  });
}

