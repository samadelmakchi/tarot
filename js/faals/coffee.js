function page(mount) {
  const box = falPage(mount, meta, () => {});
  const steps = el("ol", { class: "steps" },
    el("li", { text: "فنجان قهوه‌ات را بنوش و چند قطره آب در ته آن بریز." }),
    el("li", { text: "فنجان را روی نعلبکی بچرخان و برگردان تا تفاله خشک شود." }),
    el("li", { text: "نیت کن و دکمه را بزن تا شکل‌های فنجانت تعبیر شود." }),
  );
  box.append(el("div", { class: "panel" }, el("h3", { text: "چطور فال قهوه بگیریم؟" }), steps));
  actionFlow(box, {
    note: "",
    btnLabel: "☕ تعبیر فنجان من",
    againLabel: "فنجان دیگری تعبیر کن",
    busyLabel: "در حال برگرداندن فنجان…",
    suspense: [1600, 2600],
  }, (result) => {
    const n = 3;
    const shuffled = [...SYMBOLS].sort(() => Math.random() - 0.5).slice(0, n);
    const zones = [
      { l: "ته فنجان (گذشته)", d: "دل‌مشغولی‌های ریشه‌دار و گذشته" },
      { l: "دیواره (حال)", d: "اتفاقات این روزها و حال تو" },
      { l: "لبه فنجان (آینده)", d: "آنچه به زودی رخ می‌دهد" },
    ];
    const items = shuffled.map((sym, i) => readingItem(`${sym.s} ${sym.n} — ${zones[i].l}`, [zones[i].d, sym.m]));
    result.append(el("div", { class: "reading reveal" }, ...items),
      el("p", { class: "footer-note", text: "یادت باشد فال قهوه بیش از آنکه پیش‌گویی باشد، بهانه‌ای برای گفت‌وگو و آرامش است." }),
    );
  });
}

